#!/bin/sh
# Turn the skeleton renders (tools/render_rig.sh) into watch resources for every dog:
#   resources/animations/<dog>_<clip>/  Monkey Motion animation for the FR265
#   resources/drawables/<dog>_<mood>.png  first frame of each mood loop, drawn
#                                         under the clips (see Story.endStill)
#   resources/animations/animations.xml, resources/drawables/drawables.xml
#   source/Dogs.mc  the list of dogs and their resources, for the watch face
# Clips, in Story's order: the mood loops (awake happy sleepy), walk in, walk
# out, lie down, and get up (lie down played backwards). The launcher icon is
# left as it is.
# DOGS lists the dogs, e.g. DOGS="ozzie" for a face with only Ozzie; FRAMES
# is where the renders are (default build/frames/rig).
set -e
cd "$(dirname "$0")/.."
SDK=$(cat "$HOME/Library/Application Support/Garmin/ConnectIQ/current-sdk.cfg")
export JAVA_HOME=${JAVA_HOME:-/opt/homebrew/opt/openjdk@17/libexec/openjdk.jdk/Contents/Home}
export PATH="$JAVA_HOME/bin:$PATH"
# Crop to the dog (and its Zzz) before scaling to the watch size; in 400px
# frame units, scaled to whatever size was rendered
CROP="292*iw/400:328*ih/400:76*iw/400:62*ih/400"
WIDTH=222
HEIGHT=249
# Walking dogs fade in and out over this many pixels at the sides of the box
FADE=18
FPS=10
DOGS=${DOGS:-"millie nova ozzie"}
FRAMES=${FRAMES:-build/frames/rig}
CLIPS="awake happy sleepy walkin walkout liedown getup"
MOODS="awake happy sleepy"

capitalise() { echo "$1" | awk '{print toupper(substr($0,1,1)) substr($0,2)}'; }

# The edge fade: white, ramping to black over FADE pixels at the left and right
ffmpeg -v error -y -f lavfi -i "color=white:s=${WIDTH}x$HEIGHT" -vf \
    "geq=lum='255*min(1,min(X,W-1-X)/$FADE)':cb=128:cr=128" -frames:v 1 build/edge_fade.png

rm -rf resources/animations/*/ resources/drawables/*_awake.png resources/drawables/*_happy.png resources/drawables/*_sleepy.png
stills_mc=""
clips_mc=""
animations_xml="<animations>"
drawables_xml="<drawables>
    <bitmap id=\"LauncherIcon\" filename=\"launcher_icon.png\" />
    <!-- First frame of each mood loop, drawn under the clips -->"
for dog in $DOGS; do
    stills_mc="$stills_mc
        ["
    clips_mc="$clips_mc
        ["
    for clip in $CLIPS; do
        name="${dog}_$clip"
        id="$(capitalise "$dog")$(capitalise "$clip")"
        src=$clip
        reverse=""
        if [ "$clip" = getup ]; then
            src=liedown
            reverse="reverse,"
        fi
        frames="$FRAMES/$dog/$src/%04d.png"
        size=$(ffprobe -v error -select_streams v -show_entries stream=width -of csv=p=0 "$FRAMES/$dog/$src/0001.png")
        # Flatten onto black (the watch background), fade the box edges and
        # quantise to a GIF for Monkey Motion
        ffmpeg -v error -y -framerate $FPS -i "$frames" -f lavfi -i "color=black:s=${size}x$size:r=$FPS" \
            -loop 1 -i build/edge_fade.png -filter_complex \
            "[1][0]overlay=shortest=1,${reverse}crop=$CROP,scale=$WIDTH:$HEIGHT:flags=lanczos,format=rgb24[d];[2]format=rgb24[m];[d][m]blend=all_mode=multiply:shortest=1,split[a][b];[a]palettegen=stats_mode=full[p];[b][p]paletteuse=dither=sierra2_4a" \
            "build/$name.gif"
        rm -rf "resources/animations/$name"
        bash "${SDK}bin/monkeym" -v "build/$name.gif" -d fr265 -r ${WIDTH}x${HEIGHT} -f $FPS \
            -o "resources/animations/$name" > "build/monkeym_$name.log"
        # monkeym records the absolute source path; keep the repo free of local paths
        sed -i '' "s|# Video file: .*/build/|# Video file: build/|" "resources/animations/$name/$name.mmm"
        animations_xml="$animations_xml
    <animation id=\"${id}Animation\" filename=\"$name/$name.mmm\" />"
        clips_mc="$clips_mc Rez.Drawables.${id}Animation,"
        echo "built $name"
    done
    for mood in $MOODS; do
        name="${dog}_$mood"
        id="$(capitalise "$dog")$(capitalise "$mood")"
        ffmpeg -v error -y -i "$FRAMES/$dog/$mood/0001.png" -vf "crop=$CROP,scale=$WIDTH:$HEIGHT:flags=lanczos" \
            "resources/drawables/$name.png"
        drawables_xml="$drawables_xml
    <bitmap id=\"$id\" filename=\"$name.png\" />"
        stills_mc="$stills_mc Rez.Drawables.$id,"
    done
    stills_mc="$stills_mc ],"
    clips_mc="$clips_mc ],"
done
printf '%s\n</animations>\n' "$animations_xml" > resources/animations/animations.xml
printf '%s\n</drawables>\n' "$drawables_xml" > resources/drawables/drawables.xml
cat > source/Dogs.mc <<MC
// Generated by tools/build_art.sh from its DOGS list; don't edit by hand.
import Toybox.Lang;
import Toybox.WatchUi;

// [dog][mood], moods in the order $MOODS
function dogStills() as Array<Array<ResourceId> > {
    return [$stills_mc
    ];
}

// [dog][clip], clips in the order $CLIPS (Story's constants)
function dogClips() as Array<Array<ResourceId> > {
    return [$clips_mc
    ];
}
MC
